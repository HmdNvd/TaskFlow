import type { User, Task, TaskUser } from '@/types'

function toTaskUser(user: User): TaskUser {
  const numericId = Number(String(user.id).replace(/\D/g, ''))
  return {
    id: Number.isFinite(numericId) ? numericId : 0,
    name: user.name,
    email: user.email,
  }
}

